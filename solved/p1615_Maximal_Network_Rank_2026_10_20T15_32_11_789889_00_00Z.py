from collections import defaultdict


def adjacency(edges, n=None, reverse=False, directed=True, weighted=False):
    adj = defaultdict(dict) if weighted else defaultdict(list)
    for c in range(n or 0):
        adj[c]
    for e in edges:
        (a, b) = e[:2]
        if reverse:
            (a, b) = (b, a)
        if weighted:
            adj[a][b] = e[2]
            if not directed:
                adj[b][a] = e[2]
        else:
            adj[a].append(b)
            if not directed:
                adj[b].append(a)
    return adj


def pairs(n, type=tuple, back=False):
    if back:
        for j in range(n):
            for i in range(j):
                yield type((i, j))
        return
    for i in range(n):
        for j in range(i + 1, n):
            yield type((i, j))


class Grid(list):
    """A list of rows that also takes a (row, col) pair as an index."""

    def __getitem__(self, k):
        if type(k) is tuple:
            return list.__getitem__(self, k[0])[k[1]]
        return list.__getitem__(self, k)

    def __setitem__(self, k, v):
        if type(k) is tuple:
            list.__getitem__(self, k[0])[k[1]] = v
        else:
            list.__setitem__(self, k, v)


class Solution:
    def maximalNetworkRank(self, n: int, roads: list[list[int]]) -> int:
        _in_roads, roads = roads, Grid(roads)
        _w_roads = roads
        try:
            adj = adjacency(roads, n, directed=False)
            res = 0
            for i, j in pairs(n):
                a = [tuple(sorted((j, x))) for x in adj[j]]
                b = [tuple(sorted((i, x))) for x in adj[i]]
                s = set(a + b)
                roads = len(s)
                res = max(res, roads)
            return res
        finally:
            _in_roads[:] = _w_roads


