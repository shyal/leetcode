#!/usr/bin/env python3

# drawing_doc.py: the page of drawing functions, utils/harness/DRAWING.md,
# with one example per function and what it prints.
#
#   make drawing-doc           # regenerates it (make readme runs this too)
#
# Every output block is the real output of its example: the script runs each
# one under the venv, where sitecustomize has already loaded, and captures
# what it prints with the colours removed. Nothing is drawn by hand, so a
# change to a draw function shows up here on the next run.

