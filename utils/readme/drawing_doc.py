BLANKS = re.compile(r"\A(\s*\n)+|(\n\s*)+\Z")
ANSI = re.compile(r"\x1b\[[0-9;]*m")


def run(code):
    """What code prints, without colours."""
    import sitecustomize

    buf = io.StringIO()
    old = sitecustomize.console
    sitecustomize.console = Console(
        file=buf, color_system=None, width=100
    )
    try:
        with redirect_stdout(buf):
            exec(code, {"__builtins__": builtins})
    finally:
        sitecustomize.console = old
    text = ANSI.sub("", buf.getvalue())
    return BLANKS.sub("", "\n".join(ln.rstrip() for ln in text.split("\n")))


def main():
    out = [
        "# Drawing functions",
        "",
        "Generated by `make drawing-doc` from utils/readme/drawing_doc.py.",
        "Each output block is what the code above it prints.",
        "",
    ]
    for title, line, code in EXAMPLES:
        code = textwrap.dedent(code).strip("\n") + "\n"
        out += [f"## `{title}`", "", line, "", "```python", code.rstrip("\n"), "```"]
        out += ["", "```text", run(code), "```", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
